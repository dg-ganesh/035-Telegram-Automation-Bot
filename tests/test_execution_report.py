"""
Project : Telegram Automation Bot
Project ID : 035

Module Name : Execution Report Unit Tests

Purpose:
Test execution report creation, checkpoint recording, final status,
and report content produced by the LoggingService.
"""

import tempfile
import unittest
from pathlib import Path

from src.config import AppConfig
from src.services.logging_service import LoggingService


class TestExecutionReport(unittest.TestCase):
    """Test execution report generation and status tracking."""

    def setUp(self):
        """Initialize logging in an isolated temporary directory."""
        self.temp_directory = tempfile.TemporaryDirectory()
        self.project_root = Path(self.temp_directory.name)

        config = AppConfig(project_root=self.project_root)
        self.logging_service = LoggingService(config)
        self.logging_service.initialize()

    def tearDown(self):
        """Remove temporary files and close test log handlers."""
        logger = self.logging_service.get_logger()

        for handler in logger.handlers[:]:
            if isinstance(handler, __import__("logging").FileHandler):
                handler.close()
                logger.removeHandler(handler)
            elif isinstance(handler, __import__("logging").StreamHandler):
                logger.removeHandler(handler)

        self.temp_directory.cleanup()

    def read_report(self):
        """Read the execution report generated by the service."""
        report_path = self.project_root / "logs" / "execution_report.txt"

        self.assertTrue(report_path.exists())
        return report_path.read_text(encoding="utf-8")

    def test_execution_report_is_created(self):
        """Initialization creates the execution report."""
        report = self.read_report()

        self.assertIn("Telegram Automation Bot", report)
        self.assertIn("Overall status: RUNNING", report)

    def test_successful_checkpoint_is_recorded(self):
        """A successful checkpoint is included in the report."""
        self.logging_service.record_checkpoint(
            "Configuration loaded",
            True,
            "Configuration initialized successfully.",
        )

        report = self.read_report()

        self.assertIn("[PASS] Configuration loaded", report)
        self.assertIn(
            "Configuration initialized successfully.",
            report,
        )

    def test_failed_checkpoint_is_recorded(self):
        """A failed checkpoint is included in the report."""
        self.logging_service.record_checkpoint(
            "Connection verification",
            False,
            "Connection verification failed.",
        )

        report = self.read_report()

        self.assertIn("[FAIL] Connection verification", report)
        self.assertIn(
            "Connection verification failed.",
            report,
        )
        self.assertIn("Overall status: FAIL", report)

    def test_successful_execution_can_be_finalized(self):
        """A successful execution can be finalized with PASS."""
        self.logging_service.record_checkpoint(
            "GUI initialized",
            True,
            "Application window initialized.",
        )

        self.logging_service.finalize("PASS")
        report = self.read_report()

        self.assertIn("Overall status: PASS", report)
        self.assertIn(
            "Last successful checkpoint: GUI initialized",
            report,
        )

    def test_failed_execution_remains_failed_when_finalized(self):
        """A failed checkpoint prevents finalization as PASS."""
        self.logging_service.record_checkpoint(
            "Startup validation",
            False,
            "Startup validation failed.",
        )

        self.logging_service.finalize("PASS")
        report = self.read_report()

        self.assertIn("Overall status: FAIL", report)

    def test_invalid_final_status_is_rejected(self):
        """Unsupported final statuses raise ValueError."""
        with self.assertRaises(ValueError):
            self.logging_service.finalize("UNKNOWN")


if __name__ == "__main__":
    unittest.main()